#!/usr/bin/env python3
"""Create LaTeX macros/coordinates from the audited summary CSV."""
import csv
from pathlib import Path

root = Path(__file__).resolve().parents[2]
src = root / "research/data/derived/rpc-validation-20261004-summary.csv"
out = root / "paper/icce2027/generated/results.tex"
rows = list(csv.DictReader(src.open()))
data = {(r["condition"], r["metric"]): r for r in rows}

def val(condition, metric, field):
    return data[(condition, metric)][field]

out.parent.mkdir(parents=True, exist_ok=True)
lines = ["% Generated by research/scripts/make_paper_assets.py; do not edit."]
for c, macro in (("notebook", "Notebook"), ("arm", "Labrador"), ("rpc2", "RPC")):
    lines.append(rf"\newcommand{{\{macro}N}}{{{val(c, 'real_s', 'n_valid')}}}")
    lines.append(rf"\newcommand{{\{macro}ProcMean}}{{{float(val(c, 'real_s', 'mean')):.2f}}}")
    lines.append(rf"\newcommand{{\{macro}ProcSD}}{{{float(val(c, 'real_s', 'sample_sd')):.2f}}}")
    lines.append(rf"\newcommand{{\{macro}PromptMean}}{{{float(val(c, 'prompt_ms', 'mean')):.2f}}}")
    lines.append(rf"\newcommand{{\{macro}GenMean}}{{{float(val(c, 'generation_ms', 'mean')):.2f}}}")
    lines.append(rf"\newcommand{{\{macro}ProcMin}}{{{float(val(c, 'real_s', 'minimum')):.2f}}}")
    lines.append(rf"\newcommand{{\{macro}ProcMax}}{{{float(val(c, 'real_s', 'maximum')):.2f}}}")
    lines.append(rf"\newcommand{{\{macro}PromptSec}}{{{float(val(c, 'prompt_ms', 'mean')) / 1000:.3f}}}")
    lines.append(rf"\newcommand{{\{macro}GenSec}}{{{float(val(c, 'generation_ms', 'mean')) / 1000:.3f}}}")
    lines.append(rf"\newcommand{{\{macro}GenRate}}{{{32 / (float(val(c, 'generation_ms', 'mean')) / 1000):.2f}}}")
lines += [
    r"\newcommand{\ProcCoordinates}{(Notebook,\NotebookProcMean) (Labrador,\LabradorProcMean) (RPC--2,\RPCProcMean)}",
]
out.write_text("\n".join(lines) + "\n")
print(out)
